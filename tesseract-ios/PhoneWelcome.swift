/// The text a new Library starts with, so Play works on the first launch.
enum PhoneWelcome {
    static let title = "Welcome to Tesseract"

    static let text = """
        Welcome to Tesseract.

        Tesseract reads any text aloud, right here on your phone. Paste an article, \
        share a page from Safari, or open a document from Files, and press play.

        The word being read lights up as you listen. Tap a sentence to jump to it, and \
        drag the bar at the bottom to go anywhere in the text. Every text remembers \
        where you stopped, so a long article can wait until tomorrow.

        Nothing you read leaves this phone. Tesseract doesn't send your texts anywhere, \
        and it works without a connection.
        """
}
